const VOCAB = {};
for (const [lid, raw] of Object.entries(VOCAB_RAW)) {
  const groups = []; let g = null;
  raw.trim().split('\n').forEach(line => {
    line = line.trim(); if (!line) return;
    if (line.startsWith('## ')) { g = { name: line.slice(3), items: [] }; groups.push(g); return; }
    const [geo, ru, pos] = line.split('|'); if (g && geo && ru) g.items.push([geo.trim(), ru.trim(), (pos || '').trim()]);
  });
  VOCAB[lid] = groups;
}
